SMS = {
    "sw": (
        "Mifugo: {animal} ametibiwa kwa {product} ({given}). {milk_line} {meat_line}"
    ),
    "en": (
        "Mifugo: {animal} was treated with {product} ({given}). {milk_line} {meat_line}"
    ),
}


def _say(lang):
    return say_sw if lang == "sw" else say_en


def milk_line(status, lang="sw", ref=None):
    """One sentence for one animal's milk, from a withdrawal.AnimalStatus."""
    v = status.milk
    product = v.driving.product if v.driving else ""
    if v.status is Status.CLEAR:
        key = "clear"
    elif v.status is Status.WITHHOLD:
        key = "withhold"
    else:
        key = v.reason
    when = _say(lang)(v.safe_from, ref) if v.safe_from else ""
    return MILK[key][lang].format(animal=status.animal, when=when, product=product)


def meat_line(status, lang="sw", ref=None):
    v = status.meat
    product = v.driving.product if v.driving else ""
    key = {"clear": "clear", "withhold": "withhold"}.get(v.status.value, "unknown_period")
    when = _say(lang)(v.safe_from, ref) if v.safe_from else ""
    return MEAT[key][lang].format(animal=status.animal, when=when, product=product)


def collection_line(check, lang="sw", ref=None):
    milking = _say(lang)(check.milking_at, ref)
    names = join_names((s.animal for s in check.exclude), lang)
    return COLLECTION[check.decision][lang].format(milking=milking, animals=names)


def sms_text(status, treatment, lang="sw", ref=None):
    """The message the farmer receives after logging a treatment."""
    return SMS[lang].format(
        animal=status.animal,
        product=treatment.product,
        given=_say(lang)(treatment.given_at, ref),
        milk_line=milk_line(status, lang, ref),
        meat_line=meat_line(status, lang, ref),
    )
